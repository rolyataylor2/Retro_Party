import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";

const root = path.resolve(import.meta.dirname, "..");

test("Mini-Game Maker is a standalone emulator app without the main-app iframe", () => {
  const page = fs.readFileSync(path.join(root, "public", "mini-game-maker.html"), "utf8");
  const script = fs.readFileSync(path.join(root, "public", "mini-game-maker.js"), "utf8");

  assert.match(page, /src="\/mini-game-maker\.js"/);
  assert.doesNotMatch(page, /app\.js|iframe/i);
  assert.match(script, /BrowserEmulatorSession/);
  assert.match(script, /TasPlaybackEngine/);
  assert.match(script, /bitsToMask, firstConnectedGamepad, gamepadInputMask, nesBits/);
  assert.match(script, /api\("\/api\/controls"\)/);
  assert.match(script, /gamepadInputMask\(pad,state\.controls\.gamepad\)/);
  assert.match(script, /data-reinforce-goal/);
  assert.match(script, /data-reinforce-loss/);
  assert.match(script, /emulator\.reinforceGoal/);
  assert.match(script, /emulator\.reinforceLoss/);
  assert.match(script, /data-verify/);
  assert.match(script, /emulator\.verify\(\)/);
  assert.match(script, /emulator\.acceptVerification\(\)/);
  assert.match(script, /data-editor-tab/);
  assert.match(script, /modifierTab/);
  assert.match(script, /GOALS & RUNS/);
  assert.match(script, /label:"FINALIZE"/);
  assert.match(script, /activateEditorTab/);
  assert.match(script, /destination==="rules".*beginAttempt\("recording"\)/);
  assert.match(script, /destination==="finalize".*emulator\.verify\(\)/);
  assert.match(script, /verificationSummaryPanel/);
  assert.match(script, /state\.editorTab==="finalize"/);
  assert.match(script, /label:"SCORE"/);
  assert.match(script, /label:"EXPORT"/);
  assert.match(script, /function exportTab/);
  assert.match(script, /memoryExports/);
  assert.match(script, /data-select-export-address/);
  assert.match(script, /memory-export-form/);
  assert.match(script, /filterMemoryCandidates/);
  assert.match(script, /ScoreRunTracker/);
  assert.match(script, /data-save-score-modifier/);
  assert.match(script, /data-save-score-group/);
  assert.match(script, /scoreDraft/);
  assert.match(script, /SCORE CALCULATORS/);
  assert.match(script, /data-score-comparison/);
  const scoreTabSource = script.match(/function scoreTab\(\).*?\n/)?.[0] || "";
  assert.doesNotMatch(scoreTabSource, /data-score-filter/);
  assert.match(script, /New memory scan running/);
  assert.match(script, /emulator\.resetCreatorState\(\)/);
  assert.match(script, /function resetLoopTimer\(\)/);
  assert.match(script, /restoreCreatorStartingState=emulator\.resetCreatorState\.bind\(emulator\)/);
  assert.match(script, /emulator\.resetCreatorState=\(\.\.\.args\)=>.*resetLoopTimer\(\)/);
  assert.match(script, /data-score-reset-run/);
  assert.match(script, /Score search results preserved/);
  assert.match(script, /data-score-draft-total/);
  assert.match(script, /draftScoreTotal/);
  assert.match(script, /data-live-score-total/);
  assert.match(script, /memoryTrackedPanel/);
  assert.match(script, /memorySuggestionsPanel/);
  assert.match(script, /data-memory-new-scan/);
  assert.match(script, /data-memory-new-scan>NEW<\/button><button type="button" data-score-reset-run/);
  assert.match(script, /data-score-drag-set/);
  assert.match(script, /data-hold-score/);
  assert.match(script, /scoreEditorModal/);
  assert.match(script, /score-group-editor/);
  assert.match(script, /score-calculation-line/);
  assert.match(script, /name="address" required maxlength="6"/);
  assert.match(script, /export-group-editor/);
  assert.match(script, /name="entry-name"/);
  assert.match(script, /getAll\("entry-address"\)\.map\(parseMemoryAddress\)/);
  assert.match(script, /data-remove-saved-score/);
  assert.match(script, /score-remove-icon/);
  assert.match(script, /verifyResultModal/);
  assert.match(script, /data-edit-modifier/);
  assert.match(script, /modifierEditorModal/);
  assert.match(script, /data-lock-modifier-current/);
  assert.match(script, /name="entry-enabled"/);
  assert.match(script, /enabledEntries/);
  assert.match(script, /data-reset-modifier/);
  assert.match(script, /data-delete-modifier/);
  assert.match(script, /Delete .* from the library/);
  assert.match(script, /SAVE FOR MINI-GAME/);
  assert.match(script, /updateMiniGameModifier/);
  assert.match(script, /data-score-field="cumulative"/);
  assert.doesNotMatch(script, /modifier-value-form/);
  assert.match(script, /editorTab:"rules"/);
  assert.doesNotMatch(script, /modifier-drawer/);
  assert.match(script, /data-edit-rule/);
  assert.match(script, /data-reset-rule/);
  assert.match(script, /data-delete-rule/);
  assert.match(script, /updateMilestoneCondition/);
  assert.match(script, /updateLossGuardCondition/);
  assert.doesNotMatch(script, /verification-panel|verificationStatusMarkup/);
  assert.match(script, /startCreator/);
  assert.match(script, /challengePackage/);
  assert.match(script, /stage:"games"/);
  assert.match(script, /data-record-new/);
  assert.match(script, /data-challenge=/);
  assert.match(script, /data-go=/);
  assert.doesNotMatch(script, /data-back|workspace-heading/);
  assert.doesNotMatch(script, /data-edit-challenge|toolsView/);
  assert.doesNotMatch(script, /iframe|studioRoute|\/app\.js/i);
});
